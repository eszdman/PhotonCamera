"""Exercise production CFA resampling on EGL and measure analytic shift error.

Run tools/alignment-bench/.venv/bin/python app/src/test/python/halide_subpixel_test.py
from the repository root. Optional --report PATH writes measured sampler errors.
Truth is sampled analytically, never generated by the filter being evaluated.
"""
import argparse
import json
from pathlib import Path
import moderngl
import numpy as np

SRC = Path(__file__).resolve().parents[2]
RAW_W, RAW_H = 260, 196
MODES = ('texel_floor', 'texel_nearest', 'cfa_bilinear', 'cfa_cubic')


def weights(t):
    # Independent Keys convolution kernel (a=-1/2), evaluated at four distances.
    d = np.abs(np.arange(-1, 3).reshape(4, 1, 1) - t)
    return np.where(d <= 1, 1.5*d**3-2.5*d**2+1,
                    np.where(d < 2, -0.5*d**3+2.5*d**2-4*d+2, 0))


def reference(source, dx, dy, mode, cfa):
    h, w, _ = source.shape
    y, x = np.mgrid[:h, :w].astype('f4')
    x += dx; y += dy
    lo_x, lo_y = np.floor(x).astype(int), np.floor(y).astype(int)
    fx, fy = x-lo_x, y-lo_y
    def fetch(x, y):
        out = np.empty_like(source)
        for c in range(4):
            low = (np.array(cfa)-[c%2, c//2]+1)//2
            high = (np.array([RAW_W, RAW_H])-1+np.array(cfa)-[c%2, c//2])//2
            if mode == 0: low, high = (0, 0), (w-1, h-1)
            out[..., c] = source[np.clip(y, low[1], high[1]), np.clip(x, low[0], high[0]), c]
        return out
    if mode < 2:
        return fetch(np.floor(x+(0.5 if mode else 0)).astype(int),
                     np.floor(y+(0.5 if mode else 0)).astype(int))
    taps = [fetch(lo_x+ix, lo_y+iy) for iy in range(2) for ix in range(2)]
    if mode == 2:
        return ((taps[0]*(1-fx[..., None])+taps[1]*fx[..., None])*(1-fy[..., None])
                +(taps[2]*(1-fx[..., None])+taps[3]*fx[..., None])*fy[..., None])
    wx, wy = weights(fx), weights(fy)
    out = np.zeros_like(source)
    for iy in range(4):
        for ix in range(4):
            out += fetch(lo_x+ix-1, lo_y+iy-1)*(wx[ix]*wy[iy])[..., None]
    return np.clip(out, np.minimum.reduce(taps), np.maximum.reduce(taps))


class Renderer:
    def __init__(self, ctx, mode, tile, sampler_only=False, shader_path=None):
        self.ctx, self.mode, self.tile = ctx, mode, tile
        code = (shader_path or SRC/'main/assets/shaders/merge/mergeAlign.glsl').read_text()
        code = code.replace('#define LAYOUT //', '#define LAYOUT layout(local_size_x=8,local_size_y=8) in;')
        code = code.replace('#define TILE_AL 16', f'#define TILE_AL {tile}')
        code = code.replace('#define HALIDE_SAMPLING 0', f'#define HALIDE_SAMPLING {mode}')
        if sampler_only:
            code = code.replace('void main()', 'void mergeMain()')
            code += '''
void main() {
    ivec2 xy = ivec2(gl_GlobalInvocationID.xy);
    if (any(greaterThanEqual(xy,imageSize(outTexture)))) return;
    vec2 d = vec4ToAlignment(texelFetch(alignmentTexture,ivec2(0),0));
#if HALIDE_SAMPLING > 0
    vec4 sampleValue = sampleCfa(vec2(xy)+d);
#else
    vec4 sampleValue = imageLoad(alterTexture,clamp(xy+ivec2(floor(d)),ivec2(0),imageSize(outTexture)-1));
#endif
    imageStore(outTexture,xy,sampleValue);
}
'''
        self.program = ctx.compute_shader('#version 430\n'+code)

    def run(self, source, base, dx, dy, cfa=(0, 0), exposure=1, vectors=None):
        h, w, _ = source.shape
        aw, ah = RAW_W//self.tile+1, RAW_H//self.tile+1
        atlas = np.empty((ah, aw, 4), dtype='f2')
        atlas[:] = np.floor(dx)/(RAW_W//2), np.floor(dy)/(RAW_H//2), dx%1, dy%1
        if vectors is not None:
            whole = np.floor(vectors)
            atlas[..., :2] = whole / [RAW_W//2, RAW_H//2]
            atlas[..., 2:] = vectors - whole
        # Match production fp16 atlas decoding in the reference comparison.
        d = np.floor(atlas[0,0,:2].astype('f4')*[RAW_W//2,RAW_H//2]+0.5)+atlas[0,0,2:]
        textures = [self.ctx.texture((w,h),4,source.astype('f2').tobytes(),dtype='f2'),
                    self.ctx.texture((w,h),4,base.astype('f2').tobytes(),dtype='f2'),
                    self.ctx.texture((w,h),4,dtype='f2'),
                    self.ctx.texture((aw,ah),4,atlas.tobytes(),dtype='f2'),
                    self.ctx.texture((RAW_W,RAW_H),1,dtype='f2')]
        textures[0].bind_to_image(4,read=True,write=False)
        textures[1].bind_to_image(2,read=True,write=False)
        textures[2].bind_to_image(3,read=False,write=True)
        textures[3].use(0); textures[4].use(1)
        for name, value in dict(alignmentTexture=0,inTexture=1,rawHalf=(RAW_W//2,RAW_H//2),
                alignmentSize=(aw,ah),shift=(0,0),cfaShift=cfa,exposure=exposure,
                border=(16,16),minLevel=0.001,noiseS=0.01,noiseO=0.0001).items():
            if name in self.program: self.program[name].value = value
        self.program.run((w+7)//8,(h+7)//8)
        self.ctx.memory_barrier()
        actual = np.frombuffer(textures[2].read(),dtype='f2').astype('f4').reshape(h,w,4)
        for t in textures: t.release()
        return actual, d


def scene(x, y, frequency=0.13):
    # Distinct channel DC levels and phases expose cross-color interpolation.
    return np.stack([0.17+0.17*c+0.055*np.sin(2*np.pi*(frequency*x+0.027*y)+c*0.53)
                      +0.035*np.cos(2*np.pi*(0.041*x+frequency*0.6*y)+c*0.31)
                      for c in range(4)], axis=-1)


def checks(ctx):
    count = 0
    for tile in (16,32):
        for mode in range(4):
            sampler, merge = Renderer(ctx,mode,tile,True), Renderer(ctx,mode,tile)
            for cfa in ((0,0),(1,0),(0,1),(1,1)):
                y,x=np.mgrid[:RAW_H//2+cfa[1],:RAW_W//2+cfa[0]]
                source=scene(x,y).astype('f2').astype('f4')
                # Simulate merge00's invalid border sites with conspicuous foreign colors.
                for c in range(4):
                    low=(np.array(cfa)-[c%2,c//2]+1)//2
                    high=(np.array([RAW_W,RAW_H])-1+np.array(cfa)-[c%2,c//2])//2
                    source[(x<low[0])|(x>high[0])|(y<low[1])|(y>high[1]),c]=1-c*0.2
                source=source.astype('f2').astype('f4')
                for dx,dy in ((0,0),(2,-3),(-2,3),(0.375,-0.625),(-0.125,0.875),(11.7,-9.3)):
                    actual,d=sampler.run(source,source,dx,dy,cfa)
                    expected=reference(source,*d,mode,cfa)
                    np.testing.assert_allclose(actual,expected,atol=5e-4,rtol=0)
                    # Real production entry point: test the corrected selection gate too.
                    base=expected.astype('f2').astype('f4')
                    output,_=merge.run(source,base,dx,dy,cfa)
                    np.testing.assert_allclose(output,base,atol=1e-3,rtol=0)
                    count+=2
                black=np.zeros_like(source)
                output,_=merge.run(black,black,-0.1,0.4,cfa)
                assert np.isfinite(output).all() and np.max(np.abs(output))==0
                # Reject a bad alignment when the unshifted source equals the reference.
                output,_=merge.run(source,source,3.2,-2.4,cfa)
                np.testing.assert_allclose(output,source,atol=5e-4,rtol=0)
                count+=2
            sampler.program.release();merge.program.release()
    print(f'CFA precision/gate checks: {count} GPU shader executions passed')


def quality(ctx):
    y,x=np.mgrid[:RAW_H//2,:RAW_W//2]
    shifts=((0.125,-0.375),(0.375,-0.625),(-0.75,0.25),(0.5,0.5),(-1.125,1.875))
    report={}
    for mode in range(4):
        sampler=Renderer(ctx,mode,32,True)
        errors=[]
        for frequency in (0.05,0.13,0.23):
            truth=scene(x,y,frequency)
            for dx,dy in shifts:
                source=scene(x-dx,y-dy,frequency).astype('f2').astype('f4')
                actual,_=sampler.run(source,truth,dx,dy)
                errors.append(np.mean((actual[5:-5,5:-5]-truth[5:-5,5:-5])**2))
        # A high-contrast edge must not acquire negative/bright ringing lobes.
        step=np.repeat(np.where(x[...,None] < RAW_W//4,0.1,0.9),4,axis=2).astype('f4')
        output,_=sampler.run(step,step,0.375,0.625)
        lo,hi=float(step.astype('f2').min()),float(step.astype('f2').max())
        assert output.min()>=lo-0.0005 and output.max()<=hi+0.0005
        report[MODES[mode]]={'analytic_rmse':float(np.sqrt(np.mean(errors))),
                            'edge_min':float(output.min()),'edge_max':float(output.max())}
        sampler.program.release()
    assert report['cfa_cubic']['analytic_rmse'] < report['cfa_bilinear']['analytic_rmse']*0.75
    assert report['cfa_cubic']['analytic_rmse'] < report['texel_nearest']['analytic_rmse']*0.5
    return report


def optimized_equivalence(ctx):
    original = SRC/'androidTest/assets/shaders/mergeAlignCubicReference.glsl'
    rng = np.random.default_rng(8371)
    max_error, cases = 0.0, 0
    for tile in (16, 32):
        old = Renderer(ctx, 3, tile, shader_path=original)
        new = Renderer(ctx, 3, tile)
        ah, aw = RAW_H//tile+1, RAW_W//tile+1
        for cfa in ((0,0),(1,0),(0,1),(1,1)):
            shape = (RAW_H//2+cfa[1], RAW_W//2+cfa[0], 4)
            source = rng.uniform(0.01,0.99,shape).astype('f2').astype('f4')
            base = rng.uniform(0.01,0.99,shape).astype('f2').astype('f4')
            for kind in ('constant','varying','repeated','large'):
                vectors = rng.uniform(-3,3,(ah,aw,2)).astype('f4')
                if kind == 'constant': vectors[:] = (0.375,-0.625)
                elif kind == 'repeated': vectors[:,1::2] = vectors[:,:-1:2]
                elif kind == 'large': vectors *= 40
                a,_ = old.run(source,base,0,0,cfa,vectors=vectors)
                b,_ = new.run(source,base,0,0,cfa,vectors=vectors)
                np.testing.assert_allclose(a,b,atol=5e-4,rtol=0,
                    err_msg=f'Cubic optimization changed pixels: tile={tile} cfa={cfa} {kind}')
                max_error=max(max_error,float(np.max(np.abs(a-b))))
                cases += 1
        old.program.release();new.program.release()
    print(f'Original/optimized cubic: {cases} full shader comparisons passed, max difference={max_error}')
    return {'comparisons':cases,'max_abs_difference':max_error}


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--report',type=Path);args=parser.parse_args()
    ctx=moderngl.create_standalone_context(require=430,backend='egl')
    checks(ctx);result=quality(ctx);optimized_equivalence(ctx);ctx.release()
    print(json.dumps(result,indent=2))
    if args.report:
        args.report.write_text(json.dumps({'method':'Analytic per-CFA-plane sinusoidal scenes at 3 frequencies and 5 known shifts; original samples quantized to fp16; production shader sampler evaluated via EGL; interior RMSE. No noise or alignment estimation. Sharp step verifies bounded overshoot.',
                                          'samplers':result},indent=2)+'\n')
