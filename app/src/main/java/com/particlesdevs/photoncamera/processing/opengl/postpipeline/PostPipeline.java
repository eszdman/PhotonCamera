    private void computeNoise(Parameters parameters) {
        NoiseModeler modeler = parameters.noiseModeler;
        noiseS = modeler.computeModel[0].first.floatValue() +
                modeler.computeModel[1].first.floatValue() +
                modeler.computeModel[2].first.floatValue();
        noiseO = modeler.computeModel[0].second.floatValue() +
                modeler.computeModel[1].second.floatValue() +
                modeler.computeModel[2].second.floatValue();
        noiseS /= 3.f;
        noiseO /= 3.f;
        double noisempy = Math.pow(2.0, mSettings.noiseRstr + constShift);
        Log.d("PostPipeline", "noisempy:" + noisempy);
        noiseS *= noisempy;
        noiseO *= noisempy;
        Log.d("PostPipeline", "NoiseS:" + noiseS + "\n" + "NoiseO:" + noiseO);
        noiseO = Math.max(noiseO, Float.MIN_NORMAL);
        noiseS = Math.max(noiseS, Float.MIN_NORMAL);
    }

    public Bitmap Run(ByteBuffer inBuffer, Parameters parameters) {
        mParameters = parameters;
        mSettings = PhotonCamera.getSettings();
        Point rawSliced = parameters.rawSize;
        cropSize = new Point(parameters.rawSize);
        boolean zoomed = PhotonCamera.getCaptureController() != null
                && PhotonCamera.getCaptureController().zoomController.isZoomed();
        if (PhotonCamera.getSettings().aspect169 && !zoomed) {
            if (rawSliced.x > rawSliced.y) {
                rawSliced = new Point(rawSliced.x & ~3, (rawSliced.x * 9 / 16) & ~3);
            } else {
                rawSliced = new Point((rawSliced.y * 9 / 16) & ~3, rawSliced.y & ~3);
            }
            if (rawSliced.x < 4) rawSliced.x = 4;
            if (rawSliced.y < 4) rawSliced.y = 4;
            cropSize = new Point(rawSliced);
        }
        workSize = new Point(cropSize.x, cropSize.y);
        computeNoise(parameters);
        captureDemosaic = mSettings.ultraHdr;
        mCaptured = false;
        linearDisplayGain = 1.0f;
        sceneWhiteRaw = 0f;
        adaptiveWhitePoint = 1.0f;
        rawClipLevel = 1.0f;
        exposureCurve = null;
        Point targetSliced = new Point(rawSliced.x, rawSliced.y);
        if (parameters.fullRawSize != null && parameters.isCropped) {
            targetSliced = new Point(parameters.fullRawSize.x & ~3, parameters.fullRawSize.y & ~3);
        }
        Point rotatedSize = getRotatedCoords(targetSliced);
        if (PhotonCamera.getSettings().energySaving || mParameters.rawSize.x * mParameters.rawSize.y < ResolutionSolution.smallRes) {
            GLDrawParams.TileSize = 8;
        } else {
            GLDrawParams.TileSize = 256;
        }
        GLFormat format = new GLFormat(GLFormat.DataType.SIMPLE_8, 4);
        // The final bitmap is allocated up-front and the render is streamed
        // straight into its pixels: no intermediate full-frame native buffer
        // (~258 MB at 64 MP) and no extra copies.
        Bitmap res = Bitmap.createBitmap(rotatedSize.x, rotatedSize.y, Bitmap.Config.ARGB_8888);
        GLCoreBlockProcessing glproc = new GLCoreBlockProcessing(rotatedSize, null, format, GLDrawParams.Allocate.None);
        glint = new GLInterface(glproc);
        stackFrame = inBuffer;
        glint.parameters = parameters;

        // Inject tunable values for PostPipeline (since it doesn't extend Node)
        com.particlesdevs.photoncamera.settings.TunableInjector.inject(this);

        BuildDefaultPipeline();
        res = runAll(res);
        Allocator.logStage("PostPipeline", "post-render");

        // The linear scene buffer was already snapshotted to CPU from inside
        // Initial.Run (before closeAll claims the textures), so the
        // scene-anchored gain-map pass can measure it afterwards.
        // closeAll must run while the EGL context is still current.
        GLTexture.closeAll();
        return res;
    }

